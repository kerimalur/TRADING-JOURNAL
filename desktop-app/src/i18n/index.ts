// Lade gespeicherte Sprache oder verwende Standard
const savedLang = localStorage.getItem(STORAGE_KEYS.THEME) || LANGUAGES.DE;

i18n
  .use(initReactI18next)
  .init({
    resources: {
      de: { translation: de },
      en: { translation: en },
    },
    lng: savedLang,
    fallbackLng: LANGUAGES.DE,
    interpolation: {
      escapeValue: false,
    },
  });

export default i18n;

// Helper zum Sprachwechsel
export const changeLanguage = (lang: string) => {
  i18n.changeLanguage(lang);
  localStorage.setItem(STORAGE_KEYS.THEME, lang);
};

// Hook für Typsicherheit
export type TranslationKeys = typeof de;
